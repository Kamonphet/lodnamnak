COMP_COLS = [("F", "G"), ("H", "I"), ("J", "K"), ("L", "M")]
# คอลัมน์ค่าต่อ 100 ก. ในแท็บ "อาหาร": H kcal, I โปรตีน, J คาร์บ, K ไขมัน, L ใยอาหาร, M น้ำตาล, N โซเดียม
NUTRIENT_SRC = {"O": ("H", 0), "P": ("I", 1), "Q": ("J", 1), "R": ("K", 1), "S": ("L", 1), "T": ("M", 1), "U": ("N", 0)}


def nutrient_formula(r, src_col, digits):
    parts = [
        f"IF({c}{r}=\"\",0,XLOOKUP({c}{r},'อาหาร'!$S:$S,'อาหาร'!${src_col}:${src_col},0)*N({g}{r})/100)"
        for c, g in COMP_COLS
    ]
    return f"=ROUND({'+'.join(parts)},{digits})"


def table(oil_code):
    rows = [HEADER]
    for cid, name, kw, cat, unit, comps, extra in COMBOS:
        r = len(rows) + 1
        cells = []
        for i in range(4):
            if i < len(comps):
                code, grams = comps[i]
                cells += [code.replace("{OIL}", oil_code), grams]
            else:
                cells += ["", ""]
        row = [cid, name, kw, cat, unit] + cells + [f"=SUM(G{r},I{r},K{r},M{r})"]
        for col in "OPQRSTU":
            src, digits = NUTRIENT_SRC[col]
            row.append(nutrient_formula(r, src, digits))
        row += [NOTE + (f"; {extra}" if extra else ""), True]
        rows.append(row)
    return rows


